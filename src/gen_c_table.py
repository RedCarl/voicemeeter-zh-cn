#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""把 mempatch_*.json 转换成可直接编进 C/C++ DLL 的数据表头文件。

每个产品生成一个头文件，其中定义：
    VMZH_HOST_<PREFIX>   L"宿主 exe 名"
    VMZH_COUNT_<PREFIX>  条目数
    vmzh_<prefix>_blob   原文与新串的扁平字节池
    vmzh_<prefix>_index  索引表
其中 VMZH_ENTRY 由 vmzh_patch.h 提供。

用法:
    python src/gen_c_table.py --product potato-x86 --prefix POTATO_X86 \
        --out src/vmzh_table_potato_x86.h
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# 产品 -> 宿主 exe 名
HOSTS = {
    "potato-x86":  "voicemeeter8.exe",
    "banana-x86":  "voicemeeterpro.exe",
    "potato":      "voicemeeter8x64.exe",
    "banana":      "voicemeeterpro_x64.exe",
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--product", required=True, choices=sorted(HOSTS))
    ap.add_argument("--prefix", required=True,
                    help="C 标识符前缀，例如 POTATO_X86")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    plan = json.load(open(os.path.join(ROOT, f"mempatch_{args.product}.json"),
                          encoding="utf-8"))
    host_exe = HOSTS[args.product]
    pre = args.prefix
    low = pre.lower()
    guard = f"VMZH_TABLE_{pre}_H"

    blob = bytearray()
    index = []
    for it in plan["items"]:
        orig = bytes.fromhex(it["orig"])
        new = bytes.fromhex(it["bytes"])
        ooff = len(blob); blob += orig
        noff = len(blob); blob += new
        index.append((it["rva"], ooff, len(orig), noff, len(new)))

    L = []
    # 注释一律用 ASCII：这个文件要交给 MSVC，避免任何源码编码问题。
    L.append("/* Auto-generated by src/gen_c_table.py -- do not edit. */")
    L.append(f"/* target   : {plan['target_exe']}")
    L.append(f" * entries  : {plan['count']}")
    L.append(f" * source   : mempatch_{args.product}.json")
    L.append(" * host exe : " + host_exe)
    L.append(" *")
    L.append(" * Pure hex data tables; no non-ASCII text in this file.")
    L.append(" */")
    L.append(f"#ifndef {guard}")
    L.append(f"#define {guard}")
    L.append("")
    L.append('#include "vmzh_patch.h"')
    L.append("")
    L.append(f'#define VMZH_HOST_{pre}   L"{host_exe}"')
    L.append(f"#define VMZH_COUNT_{pre}  {len(index)}")
    L.append("")
    L.append(f"static const unsigned char vmzh_{low}_blob[{len(blob)}] = {{")
    for i in range(0, len(blob), 16):
        L.append("    " + ",".join(f"0x{b:02x}" for b in blob[i:i + 16]) + ",")
    L.append("};")
    L.append("")
    L.append(f"static const VMZH_ENTRY vmzh_{low}_index[{len(index)}] = {{")
    for rva, ooff, olen, noff, nlen in index:
        L.append(f"    {{0x{rva:08x}u,{ooff}u,{olen}u,{noff}u,{nlen}u}},")
    L.append("};")
    L.append("")
    L.append(f"#endif /* {guard} */")

    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L) + "\n")
    print(f"已生成 {os.path.basename(args.out)}: "
          f"宿主 {host_exe}, {len(index)} 项, 字节池 {len(blob):,} B, "
          f"文件 {os.path.getsize(args.out):,} B")
    return 0


if __name__ == "__main__":
    sys.exit(main())
